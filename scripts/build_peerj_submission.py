"""Assemble the PeerJ Computer Science upload folder:
  manuscript PDF + LaTeX source, figures as separate numbered files (order of first appearance),
  tables as separate numbered .tex files, Supplemental Code S1 (<30 MB) and Supplemental Data S2
  (<30 MB; additional prediction files), with a total below 50 MB."""
import os, re, shutil, zipfile, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); MS = f"{ROOT}/manuscript"
OUT = sys.argv[1] if len(sys.argv) > 1 else f"{ROOT}/peerj_submission"
shutil.rmtree(OUT, ignore_errors=True); os.makedirs(f"{OUT}/figures"); os.makedirs(f"{OUT}/tables"); os.makedirs(f"{OUT}/latex_source/tables")
body = open(f"{MS}/body.tex").read()
items = re.findall(r"\\begin\{(figure|table)\}(.*?)\\end\{\1\}", body, re.S)
fn, tn, log = 0, 0, []
for kind, blk in items:
    if kind == "figure":
        fn += 1; gs = re.findall(r"\\includegraphics\[[^\]]*\]\{\.\./figures/([^}]+)\.pdf\}", blk)
        if len(gs) == 1:
            shutil.copy(f"{ROOT}/figures/{gs[0]}.pdf", f"{OUT}/figures/Figure {fn}.pdf")
        else:  # multi-panel figure: combine panels side by side into one PNG at 300 dpi
            from PIL import Image
            ims = [Image.open(f"{ROOT}/figures/{g}.png").convert("RGB") for g in gs]
            h = max(i.height for i in ims); ims = [i.resize((int(i.width * h / i.height), h)) for i in ims]
            c = Image.new("RGB", (sum(i.width for i in ims) + 40 * (len(ims) - 1), h), "white"); x = 0
            for i in ims: c.paste(i, (x, 0)); x += i.width + 40
            c.save(f"{OUT}/figures/Figure {fn}.png", dpi=(300, 300))
        log.append(f"Figure {fn}: {', '.join(gs)}")
    else:
        tn += 1; ts = re.findall(r"\\input\{tables/([^}]+)\}", blk); cap = re.search(r"\\caption\{(.*?)\}\\label", blk, re.S)
        src = open(f"{MS}/tables/{ts[0]}.tex").read()
        open(f"{OUT}/tables/Table {tn}.tex", "w").write(f"% Table {tn}: {cap.group(1) if cap else ''}\n% Requires booktabs; numbers are final values.\n" + src)
        log.append(f"Table {tn}: {ts[0]}")
for f in ["main_peerj.pdf", "main_peerj.tex", "numbers.tex", "references.bib", "main_peerj.bbl"]:
    shutil.copy(f"{MS}/{f}", f"{OUT}/latex_source/{f}")
open(f"{OUT}/latex_source/body.tex", "w").write(body.replace("../figures/", "figures/"))
for t in os.listdir(f"{MS}/tables"): shutil.copy(f"{MS}/tables/{t}", f"{OUT}/latex_source/tables/{t}")
shutil.copytree(f"{ROOT}/figures", f"{OUT}/latex_source/figures")
shutil.copy(f"{MS}/main_peerj.pdf", f"{OUT}/Manuscript.pdf")
open(f"{OUT}/latex_source/README.txt", "w").write("Compile in this folder: pdflatex main_peerj; bibtex main_peerj; pdflatex main_peerj; pdflatex main_peerj\n")
EXCL_DIRS = {"data", "logs", "peerj_submission", "manuscript", "manuscript_suggestions", "__pycache__", "preds_sensitivity", "preds_tuning_v2", "preds_dp_draws", "models", "preds", "preds_gnn"}
def add_tree(z, base, arc, excl=EXCL_DIRS):
    for d, ds, fs in os.walk(base):
        ds[:] = [x for x in ds if x not in excl and not x.startswith(".git")]
        for f in fs:
            p = os.path.join(d, f)
            if "/data/second_dataset" in p or f.endswith((".mat", ".zip")) or "onesided" in f or "INVALID" in f: continue
            z.write(p, os.path.join(arc, os.path.relpath(p, base)))
with zipfile.ZipFile(f"{OUT}/Supplemental Code S1.zip", "w", zipfile.ZIP_DEFLATED) as z:
    add_tree(z, ROOT, "code_and_results")
    for f in ["dataset_manifest.json", "dataset_audit.json", "class_by_timestep.csv"]:
        if os.path.exists(f"{ROOT}/data/{f}"): z.write(f"{ROOT}/data/{f}", f"code_and_results/data/{f}")
    add_tree(z, f"{ROOT}/results/preds", "code_and_results/results/preds", excl={"__pycache__"})   # main Elliptic predictions
with zipfile.ZipFile(f"{OUT}/Supplemental Data S2.zip", "w", zipfile.ZIP_DEFLATED) as z:
    for sub in ["second_dataset/preds", "second_dataset/preds_gnn", "preds_tuning_v2", "preds_dp_draws"]:
        p = f"{ROOT}/results/{sub}"
        if os.path.isdir(p): add_tree(z, p, f"results/{sub}", excl={"__pycache__"})
# results/preds_sensitivity and results/models are regenerated by experiments/refit_fusion.py and experiments/robustness.py
# and belong in the Zenodo deposit only (PeerJ supplementary limit: 30 MB per file, 50 MB total).
sizes = {f: os.path.getsize(f"{OUT}/{f}") / 2**20 for f in ["Supplemental Code S1.zip", "Supplemental Data S2.zip"]}
open(f"{OUT}/MANIFEST.txt", "w").write("\n".join(log) + "\n" + "\n".join(f"{k}: {v:.1f} MB" for k, v in sizes.items()) + "\n")
print("\n".join(log)); print(sizes); assert all(v < 30 for v in sizes.values()) and sum(sizes.values()) < 50, "PeerJ size limits exceeded"
